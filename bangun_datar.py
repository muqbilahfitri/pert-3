
print("=== BANGUN DATAR SEGITIGA ===")

panjang = float(input("Masukkan panjang (alas) segitiga: "))
lebar = float(input("Masukkan lebar (tinggi) segitiga: "))

sisi1 = float(input("Masukkan sisi pertama: "))
sisi2 = float(input("Masukkan sisi kedua: "))

luas = panjang * lebar / 2
keliling = panjang + sisi1 + sisi2

print("Luas segitiga adalah", luas)
print("Keliling segitiga adalah", keliling)
